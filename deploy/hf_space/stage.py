"""Assemble the one site as a private Hugging Face Space, and optionally upload it.

Two private repos on the owner's account:

- ``<user>/vulnloc-weights`` (model repo) — the files below ``artifacts/`` that the site
  reads, at the same relative paths: the bundle of record, the Phase 3 and Phase 4
  checkpoints with their configs, both vocabularies and the small JSON reports. About 1.06 GB:
  the two checkpoints go up **without their optimizer state** (two-thirds of each file,
  which ``frontend/`` never reads — it loads ``model_state`` only). Every other key, and
  every weight, is unchanged; the files under ``artifacts/`` are not touched.
- ``<user>/vulnloc`` (Docker Space) — ``src/``, ``frontend/``, ``configs/``, this
  directory's Dockerfile, ``start.py`` and Space card, and a ``requirements.txt`` made
  from ``requirements.lock.txt`` with torch's CUDA build swapped for the CPU one.

Run::

    python deploy/hf_space/stage.py                  # assemble and check only; uploads nothing
    python deploy/hf_space/stage.py --upload --user <hf-user>          # the weights only
    python deploy/hf_space/stage.py --upload --space --user <hf-user>  # and the Space (needs PRO)

``--upload`` needs a write token (``hf auth login``, or ``HF_TOKEN``). The Space reads the
private weights with its own ``HF_TOKEN`` secret: set ``VULNLOC_SPACE_READ_TOKEN`` to a
read-only token and the script stores it, otherwise add it by hand under the Space's
Settings -> Variables and secrets. **A private Space is visible only to its owner and
members of its organization.**
"""

from __future__ import annotations

import argparse
import ctypes
import os
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
ARTIFACTS = REPO / "artifacts"

SEMANTIC_RUN = "fc902107a6824fad80e3036a01e8b0f1"
STRUCTURAL_RUN = "77370d569f0c4447a16c4e03c5984bb2"

WEIGHT_PATTERNS = [
    "serving/ba7dcc5f-r2/**/*",
    f"checkpoints/{SEMANTIC_RUN}/best.pt",
    f"mlartifacts/{SEMANTIC_RUN}/artifacts/config/resolved.yaml",
    f"checkpoints/{STRUCTURAL_RUN}/best.pt",
    f"mlartifacts/{STRUCTURAL_RUN}/artifacts/config/resolved.yaml",
    "representation/node_vocab_ast.json",
    "representation/subtoken_vocab_ast.json",
    "representation/label_leakage.json",
    "representation/report_ast.json",
    "data/splits/split_report.json",
    "data/cache/shards.json",
    "phase3/seed_report_semantic.json",
    "phase4/seed_report_structural.json",
    "phase5/seed_report_fused_*.json",
    "screening/verdicts_val.json",
]
"""Every file below ``artifacts/`` that ``frontend/`` opens, as ``Path.glob`` patterns."""

SLIMMED = {f"checkpoints/{SEMANTIC_RUN}/best.pt", f"checkpoints/{STRUCTURAL_RUN}/best.pt"}
"""Checkpoints uploaded without ``optimizer_state``."""

SPACE_DIRS = ["src", "frontend", "configs"]
SPACE_FILES_FROM_HERE = ["Dockerfile", "start.py", "README.md"]

DROPPED_FROM_LOCK = {
    # Windows-only, or development tooling the site never imports.
    "pywin32",
    "black",
    "ruff",
    "mypy",
    "mypy_extensions",
    "pre_commit",
    "pytest",
    "pytest_cov",
    "hypothesis",
    "import_linter",
    "pandas_stubs",
}


def _normalized(name: str) -> str:
    return name.lower().replace("-", "_")


def requirements_from_lock() -> str:
    """The lock file's pins for Linux, with torch's ``+cu130`` build swapped for ``+cpu``.

    Returns:
        The text of ``requirements.txt``.

    Raises:
        ValueError: If the lock file has no torch pin to rewrite.
    """
    lines = []
    torch_seen = False
    for raw in (REPO / "requirements.lock.txt").read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        name = line.split("==", 1)[0]
        if _normalized(name) in DROPPED_FROM_LOCK:
            continue
        if _normalized(name) == "torch":
            line = line.split("+", 1)[0] + "+cpu"
            torch_seen = True
        if _normalized(name) == "vulnloc" or line.startswith("-e "):
            continue
        lines.append(line)
    if not torch_seen:
        raise ValueError("requirements.lock.txt has no torch pin")
    header = "# Generated by deploy/hf_space/stage.py from requirements.lock.txt.\n"
    return header + "\n".join(lines) + "\n"


def weight_files() -> list[Path]:
    """Resolve :data:`WEIGHT_PATTERNS` against ``artifacts/``.

    Returns:
        Every matching file.

    Raises:
        FileNotFoundError: If any pattern matches nothing.
    """
    files: list[Path] = []
    for pattern in WEIGHT_PATTERNS:
        matched = [p for p in ARTIFACTS.glob(pattern) if p.is_file()]
        if not matched:
            raise FileNotFoundError(f"artifacts/{pattern} matches no file")
        files.extend(matched)
    return files


def stage_weights(files: list[Path], out: Path) -> None:
    """Lay the weight files out under ``out`` at their paths below ``artifacts/``.

    Unchanged files are hard links (no copy; ``out`` is on the same disk). The checkpoints
    in :data:`SLIMMED` are rewritten without ``optimizer_state``, and the slim copy is
    checked against the original weight by weight. An existing staged file is kept, so a
    resumed upload sees the same bytes.

    Args:
        files: The weight files, from :func:`weight_files`.
        out: Staging directory.

    Raises:
        ValueError: If a slimmed checkpoint's weights differ from the original's.
    """
    import torch

    for src in files:
        rel = src.relative_to(ARTIFACTS).as_posix()
        dst = out / rel
        if dst.exists():
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        if rel not in SLIMMED:
            os.link(src, dst)
            continue
        payload = torch.load(src, map_location="cpu", weights_only=False, mmap=True)
        slim = {k: v for k, v in payload.items() if k != "optimizer_state"}
        tmp = dst.with_suffix(".tmp")
        torch.save(slim, tmp)
        again = torch.load(tmp, map_location="cpu", weights_only=False)
        original = payload["model_state"]
        if again["model_state"].keys() != original.keys() or not all(
            torch.equal(again["model_state"][k], original[k]) for k in original
        ):
            raise ValueError(f"slimmed {rel} does not match its original")
        tmp.replace(dst)


def assemble_space(out: Path) -> None:
    """Copy the Space's files into a fresh ``out``.

    Args:
        out: Directory to create; replaced if it exists.
    """
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", "*.egg-info")
    for name in SPACE_DIRS:
        shutil.copytree(REPO / name, out / name, ignore=ignore)
    for name in SPACE_FILES_FROM_HERE:
        shutil.copy2(HERE / name, out / name)
    shutil.copy2(REPO / "pyproject.toml", out / "pyproject.toml")
    (out / "requirements.txt").write_text(requirements_from_lock(), encoding="utf-8")


def upload(user: str, space_dir: Path, weights_dir: Path, space: bool) -> None:
    """Upload the weights to their private model repo, and the Space when asked.

    Args:
        user: Hugging Face user or organization.
        space_dir: The assembled Space directory.
        weights_dir: The staged weights, from :func:`stage_weights`.
        space: Also create and upload the Docker Space. Since 2026-10-19 Hugging Face
            refuses a Docker Space on free CPU without PRO (HTTP 402); the site runs in a
            GitHub Codespace instead, which needs the weights only.
    """
    from huggingface_hub import HfApi

    if sys.platform == "win32":
        # The first resumable upload hung for hours after the laptop slept (2026-10-19).
        # ES_CONTINUOUS | ES_SYSTEM_REQUIRED: no idle sleep while this process lives; the
        # power settings themselves are untouched. Closing the lid still sleeps.
        ctypes.windll.kernel32.SetThreadExecutionState(0x80000000 | 0x00000001)

    api = HfApi()
    weights_repo = f"{user}/vulnloc-weights"
    space_repo = f"{user}/vulnloc"

    api.create_repo(weights_repo, repo_type="model", private=True, exist_ok=True)
    # Resumable: on a slow or flaky connection the first plain upload_folder died partway
    # (2026-10-19) and committed nothing. This one keeps its progress in
    # <weights_dir>/.cache/huggingface/ and a re-run continues from there.
    api.upload_large_folder(
        repo_id=weights_repo,
        repo_type="model",
        folder_path=weights_dir,
        private=True,
        num_workers=2,
    )

    print(f"Weights: https://huggingface.co/{weights_repo}")
    if not space:
        return

    api.create_repo(space_repo, repo_type="space", space_sdk="docker", private=True, exist_ok=True)
    api.add_space_variable(space_repo, "VULNLOC_WEIGHTS_REPO", weights_repo)
    read_token = os.environ.get("VULNLOC_SPACE_READ_TOKEN")
    if read_token:
        api.add_space_secret(space_repo, "HF_TOKEN", read_token)
    api.upload_folder(
        repo_id=space_repo,
        repo_type="space",
        folder_path=space_dir,
        commit_message="VulnLoc site",
    )
    print(f"Space:   https://huggingface.co/spaces/{space_repo}")
    if not read_token:
        print(
            "Add a read token as the Space secret HF_TOKEN (Settings -> Variables and "
            "secrets), or the Space cannot download the private weights."
        )


def main() -> None:
    """Assemble, check, and upload when asked."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--out", type=Path, default=ARTIFACTS / "hf_space" / "space")
    parser.add_argument("--weights-out", type=Path, default=ARTIFACTS / "hf_space" / "weights")
    parser.add_argument("--upload", action="store_true")
    parser.add_argument("--user", help="Hugging Face user or organization (with --upload)")
    parser.add_argument("--space", action="store_true", help="also upload the Docker Space (PRO)")
    args = parser.parse_args()

    files = weight_files()
    size = sum(p.stat().st_size for p in files)
    print(f"Weights: {len(files)} files, {size / 1e9:.2f} GB below artifacts/")
    stage_weights(files, args.weights_out)
    staged = [p for p in args.weights_out.rglob("*") if p.is_file() and ".cache" not in p.parts]
    print(f"Staged: {len(staged)} files, {sum(p.stat().st_size for p in staged) / 1e9:.2f} GB")
    assemble_space(args.out)
    print(f"Space assembled at {args.out}")

    if args.upload:
        if not args.user:
            parser.error("--upload needs --user")
        upload(args.user, args.out, args.weights_out, args.space)


if __name__ == "__main__":
    main()
